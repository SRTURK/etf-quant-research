def table(df, cols, labels, percent=()):
    lines=['| '+' | '.join(labels)+' |','|'+'|'.join(['---']*len(cols))+'|']
    for _,row in df.iterrows():
        cells=[]
        for c in cols:
            v=row[c]
            cells.append(f'{v:.2%}' if c in percent else (f'{v:.3f}' if isinstance(v,float) else str(v)))
        lines.append('| '+' | '.join(cells)+' |')
    return '\n'.join(lines)

